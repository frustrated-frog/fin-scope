package com.finscope.common.enums.investmentobservation;

public enum ReactionEventSubtype {
    EARNINGS_FORECAST, EARNINGS_REVISION, EARNINGS_REPORT, CONTRACT_SIGNED,
    CONTRACT_PROPOSED, CONTRACT_DENIED, CONTRACT_AWARDED, CONTRACT_TERMINATED, CONTRACT_AMENDED,
    REPURCHASE_PLAN, REPURCHASE_FINANCING, REPURCHASE_SHAREHOLDERS,
    REPURCHASE_PROGRESS, REPURCHASE_COMPLETED, REPURCHASE_TERMINATED,
    OPERATING_UPDATE, UNCLASSIFIED;

    public boolean isSpecific() {
        return this != OPERATING_UPDATE && this != UNCLASSIFIED;
    }
}
