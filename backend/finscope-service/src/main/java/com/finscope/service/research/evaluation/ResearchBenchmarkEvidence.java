package com.finscope.service.research.evaluation;

public class ResearchBenchmarkEvidence {
    private String ref;
    private String sourceIdentity;
    private String sourceName;
    private String sourceTier;
    private String title;
    private String publishedAt;
    private String url;
    private String excerpt;
    private String stance;

    public String getRef() { return ref; }
    public void setRef(String ref) { this.ref = ref; }
    public String getSourceIdentity() { return sourceIdentity; }
    public void setSourceIdentity(String sourceIdentity) { this.sourceIdentity = sourceIdentity; }
    public String getSourceName() { return sourceName; }
    public void setSourceName(String sourceName) { this.sourceName = sourceName; }
    public String getSourceTier() { return sourceTier; }
    public void setSourceTier(String sourceTier) { this.sourceTier = sourceTier; }
    public String getTitle() { return title; }
    public void setTitle(String title) { this.title = title; }
    public String getPublishedAt() { return publishedAt; }
    public void setPublishedAt(String publishedAt) { this.publishedAt = publishedAt; }
    public String getUrl() { return url; }
    public void setUrl(String url) { this.url = url; }
    public String getExcerpt() { return excerpt; }
    public void setExcerpt(String excerpt) { this.excerpt = excerpt; }
    public String getStance() { return stance; }
    public void setStance(String stance) { this.stance = stance; }
}
